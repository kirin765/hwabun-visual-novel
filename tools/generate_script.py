#!/usr/bin/env python3
"""Compile S01–S04, preserving dialogue and the two C01 branches verbatim."""
import hashlib, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / '1화대본.md').read_text()
body = source.split('## S01 ', 1)[1].split('## 제작 확인 메모', 1)[0]
body = '## S01 ' + body
events = []
for chunk in re.split(r'\n\s*\n', body.strip()):
    if chunk.startswith('### '):
        events.append(dict(kind='branch', text=chunk[4:]))
    elif chunk.startswith('## '):
        events.append(dict(kind='scene', text=chunk[3:]))
    elif chunk.startswith('['):
        for line in chunk.splitlines():
            assert line.startswith('[') and line.endswith(']'), line
            events.append(dict(kind='direction', text=line[1:-1]))
    else:
        who, text = chunk.split(': ', 1)
        assert who in ['미란 속말', '미란', '세란', '옥녀', '현마', '단주', '라디오', '운전수'], who
        events.append(dict(kind='thought' if who.endswith('속말') else 'spoken', who=who, text=text))

# Directions are mapped explicitly: unexpected edits require a conscious update.
D = [e['text'] for e in events if e['kind']=='direction']
actions = [
    ['scene bg garden', 'with fade'],
    ['play ambience "audio/leaves.ogg" fadein 1.0', 'play birds "audio/birds.ogg" fadein 1.0', 'play music "audio/main_gymnopedie.ogg" fadein 2.0'],
    ['show miran neutral at miran_left', 'show seran playful at seran_right', 'with dissolve'],
    ['show miran playful', 'with dissolve'],
    ['scene cg sisters', 'with dissolve'],
    ['scene bg garden', 'show miran playful at miran_left', 'show seran neutral at seran_right', 'with dissolve'],
    ['show miran hopeful', 'with dissolve'],
    ['stop music fadeout 1.0', 'stop birds fadeout 0.3', 'pause 1.8', 'play music "audio/main_gymnopedie.ogg" fadein 2.0', 'play birds "audio/birds.ogg" fadein 2.0'],
    ['play sound "audio/steps.ogg"', 'show miran playful', 'with dissolve'],
    ['play sound "audio/grass.ogg"', '$ renpy.music.set_volume(0.45, 0.8, channel="music")'],
    ['scene bg garden at bush_close', 'show miran neutral at miran_left', 'with dissolve'],
    ['play sound "audio/grass.ogg"', 'stop music fadeout 0.3', 'show snake at snake_cross', 'pause 1.8', 'hide snake'],
    ['show miran startled', 'show seran unsettled at seran_right', 'with dissolve'],
    ['pause 0.7'],
    ['play sound "audio/steps.ogg"', 'scene bg corridor', 'show miran startled at miran_left', 'show seran neutral at seran_middle', 'show oknyeo neutral at oknyeo_right', 'with fade', 'play sound "audio/door.ogg"', '$ renpy.music.set_volume(0.16, 1.0, channel="ambience")', 'stop birds fadeout 1.0'],
    ['play sound "audio/glass.ogg"'],
    ['show miran startled', 'with dissolve'],
    ['show seran neutral', 'with dissolve'],
    ['show oknyeo neutral', 'with dissolve'],
    ['show oknyeo wry', 'with dissolve'],
    ['play sound "audio/glass.ogg"', 'scene black', 'with fade', 'show text "잠시 뒤" at truecenter', 'pause 1.5', 'hide text', 'scene bg corridor', 'with fade'],
    ['play sound "audio/car.ogg"', 'stop music fadeout 1.0', 'pause 3.0'],
]
from s34_directions import directions
direction_map=dict(zip(D[:len(actions)],actions))
for direction in D[len(actions):]:
    direction_map[direction] = directions(direction)
lines=['# Generated by tools/generate_script.py. Edit the source screenplay, not this file.', 'label start:', '    $ sample_complete = False', '    $ c01_choice = None', '    $ renpy.music.set_volume(1.0, channel="music")', '    $ renpy.music.set_volume(1.0, channel="ambience")']
counter=0
for e in events:
    if e['kind']=='scene':
        scene_number = e['text'].split()[0].lower()
        if scene_number != 's01':
            lines += [f'label sample_{scene_number}:', '    $ sample_complete = False', '    $ renpy.music.set_volume(1.0, channel="music")']
        lines += ['    $ scene_title = '+json.dumps(e['text'],ensure_ascii=False)]
    elif e['kind']=='branch':
        if e['text'] == 'C01 선택':
            lines += ['    menu:', '        "아까 입 열지 말라구 했잖우.":', '            $ c01_choice = "A"', '            jump c01_a', '        "내 얘기가 그리두 우스워요?":', '            $ c01_choice = "B"', '            jump c01_b']
        elif e['text'] == 'A 경로':
            lines += ['label c01_a:']
        elif e['text'] == 'B 경로':
            lines += ['label c01_b:']
        elif e['text'] == '공통 합류':
            lines += ['label c01_join:']
        else:
            raise ValueError(e)
    elif e['kind']=='direction':
        lines += ['    # '+e['text']] + ['    '+a for a in direction_map[e['text']]]
    else:
        counter+=1
        e['id']=f'sample_{counter:03}'
        who={'미란 속말':'inner','미란':'miran','세란':'seran','옥녀':'oknyeo','현마':'hyunma','단주':'danju','라디오':'radio','운전수':'driver'}[e['who']]
        lines += [f'    $ block_id = {counter}', '    '+who+' '+json.dumps(e['text'],ensure_ascii=False)+' id '+e['id']]
lines += ['    $ sample_complete = True','    stop music fadeout 1.0','    stop ambience fadeout 1.0','    stop birds fadeout 1.0','    stop sound','    scene black','    with fade','    call screen sample_end','    return','']
(ROOT/'sample/game/story.rpy').write_text('\n'.join(lines))
spoken=[e for e in events if e['kind'] in ('spoken','thought')]
chars=sum(len(e['text'].replace('\n','')) for e in spoken)
report=dict(source_sha256=hashlib.sha256(source.encode()).hexdigest(),blocks=len(spoken),characters=chars,reading_minutes_350_to_550=[round(chars/550,2),round(chars/350,2)],events=events)
(ROOT/'sample/tests/source-manifest.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
print(f'{counter} blocks; {chars} characters; {len(D)} directions')
